"""
Unit coverage for the host-library primitives (#1230): `Models.bind!` and `Migrations.ensure_table!`.

A library that ships its own infrastructure tables on top of PormG (a live-timing feed table, say)
needed two operations PormG had only as internals: bind one model to a key and nothing else —
`set_models` also registers a module, injects constants, may load a folder and wires reverse
accessors — and create a table outside the migration flow, which meant calling
`Dialect.create_table`/`create_index` directly. A signature change in those internals breaks such a
library at `using`, not at `using PormG`. No live database: PostgreSQL statements are asserted on an offline key, and SQLite
runs on `:memory:`.
"""

using Test
using PormG
import PormG: Configuration, Models, Migrations
import DataFrames: DataFrame

_host1230_timing(; indexes = []) = Models.Model("live_timing",
  id    = Models.IDField(),
  driverref = Models.CharField(max_length = 64),
  payload   = Models.TextField(null = true);
  indexes = indexes)

function _host1230_sqlite(f; change_db::Bool = true)
  mktempdir() do root
    mkpath(joinpath(root, "host1230_db"))
    write(joinpath(root, "host1230_db", "connection.yml"),
          "test:\n  adapter: SQLite\n  database: \":memory:\"\n  config:\n" *
          "    change_db: $(change_db)\n    change_data: true\n")
    key = Configuration.load("host1230_db"; root = root, env = "test")
    try
      f(key)
    finally
      Configuration.unregister_connection(key)
    end
  end
end

# ─────────────────────────────────────────────────────────────────────────────
# Models.bind! binds one model and nothing else
# What it tests: an unloaded key raises `InvalidConfigurationError` naming the `load` call and loads
#   nothing (the #1226 rule); a loaded key sets the binding and returns the model; a model with no
#   table name is refused; no module is registered. No SQL.
# Why it matters: binding one model otherwise means assigning the `connect_key` field by hand,
#   because `set_models` does far more than bind — a struct layout, not a contract.
# ─────────────────────────────────────────────────────────────────────────────
@testset "Models.bind! binds one model and nothing else (#1230)" begin
  timing = _host1230_timing()
  err = try
    Models.bind!(timing, "host1230_unloaded")
    nothing
  catch e
    e
  end
  @test err isa PormG.InvalidConfigurationError
  @test occursin("PormG.Configuration.load(\"host1230_unloaded\"; env = ", sprint(showerror, err))
  @test !Configuration.is_loaded("host1230_unloaded")
  @test Models.connection_key(timing) === nothing

  registered = copy(Models.REGISTERED_MODULES)
  try
    Configuration.register_offline("host1230_offline")
    @test Models.bind!(timing, "host1230_offline") === timing
    @test Models.connection_key(timing) == "host1230_offline"
    @test Models.REGISTERED_MODULES == registered          # no module registered

    unnamed = Models.Model(id = Models.IDField())
    @test_throws PormG.InvalidConfigurationError Models.bind!(unnamed, "host1230_offline")
  finally
    Configuration.unregister_connection("host1230_offline")
  end
end

# ─────────────────────────────────────────────────────────────────────────────
# ensure_table!'s DDL is a migration's DDL, per engine
# What it tests: `_ensure_table_statements` renders what a migration emits for a new model —
#   PostgreSQL:
#     CREATE TABLE IF NOT EXISTS "live_timing" (… "driverref" varchar(64) NOT NULL, …);
#     CREATE INDEX "live_timing_driverref_like" ON "live_timing" ("driverref" text_pattern_ops);
#     COMMENT ON INDEX "live_timing_driverref_like" IS 'pormg:index';
#   `indexes = false` keeps only the table. On SQLite an opclass index is refused with
#   `BackendCapabilityError`, as `makemigrations` refuses it. A dotted `db_table`
#   (`"telemetry.lap_times"`) is quoted whole on both engines, never as `"telemetry"."lap_times"` (#1254).
# Why it matters: a host could not express an opclass through `Dialect.create_index`'s internal
#   signature; through the model's own `Index(...; opclasses)` it is the same rendering migrate uses.
# ─────────────────────────────────────────────────────────────────────────────
@testset "ensure_table! renders a migration's DDL per engine (#1230)" begin
  like = Models.Index(fields = ("driverref",), name = "live_timing_driverref_like", opclasses = ("text_pattern_ops",))
  try
    Configuration.register_offline("host1230_pg"; adapter = :postgres)
    Configuration.register_offline("host1230_sl"; adapter = :sqlite)
    pg = PormG.config["host1230_pg"].connections
    sl = PormG.config["host1230_sl"].connections

    table_pg = "CREATE TABLE IF NOT EXISTS \"live_timing\" (\n" *
               "  \"id\" bigint PRIMARY KEY UNIQUE NOT NULL GENERATED BY DEFAULT AS IDENTITY,\n" *
               "  \"driverref\" varchar(64) NOT NULL,\n" *
               "  \"payload\" text NULL\n);"
    @test Migrations._ensure_table_statements(pg, _host1230_timing(indexes = [like])) == [
      table_pg,
      "CREATE INDEX \"live_timing_driverref_like\" ON \"live_timing\" (\"driverref\" text_pattern_ops);\n" *
      "COMMENT ON INDEX \"live_timing_driverref_like\" IS 'pormg:index';",
    ]
    @test Migrations._ensure_table_statements(pg, _host1230_timing(indexes = [like]); indexes = false) == [table_pg]

    @test_throws PormG.BackendCapabilityError Migrations._ensure_table_statements(sl, _host1230_timing(indexes = [like]))

    # #1254: a dotted `db_table` is ONE identifier, quoted whole — the name `_live_table_exists`
    # looks up whole too (`to_regclass(quote_ident($1))`). It is not split into a schema and a table.
    dotted = Models.Model("live_timing", db_table = "telemetry.lap_times",
                          id = Models.IDField(), driverref = Models.CharField(max_length = 64, db_index = true))
    for conn in (pg, sl)
      statements = Migrations._ensure_table_statements(conn, dotted)
      @test startswith(statements[1], "CREATE TABLE IF NOT EXISTS \"telemetry.lap_times\" (")
      @test any(s -> occursin("ON \"telemetry.lap_times\"", s) && occursin("CREATE INDEX", s), statements)
      @test !any(s -> occursin("\"telemetry\".\"lap_times\"", s), statements)
    end
  finally
    Configuration.unregister_connection("host1230_pg")
    Configuration.unregister_connection("host1230_sl")
  end
end

# ─────────────────────────────────────────────────────────────────────────────
# ensure_table! on SQLite: created once, then left alone
# What it tests: the first call returns `:created` and the table and its index exist
#   (`sqlite_master`); the second returns `:exists` and changes nothing; a `change_db: false`
#   connection returns `:disabled` with a warning and creates nothing; an unloaded key raises
#   `InvalidConfigurationError`; inside an open transaction it raises `TransactionError`.
#   SQLite `:memory:`: sequential calls reuse the pool's first slot, so every call sees one database.
# Why it matters: a host runs this on every boot; it must be idempotent and must respect the same
#   `change_db` gate `migrate` does.
# ─────────────────────────────────────────────────────────────────────────────
@testset "ensure_table! on SQLite: created once, then left alone (#1230)" begin
  pair = Models.Index(fields = ("driverref", "payload"), name = "live_timing_driverref")
  _host1230_sqlite() do key
    timing = _host1230_timing(indexes = [pair])
    Models.bind!(timing, key)
    @test Migrations.ensure_table!(timing, key) === :created
    conn = PormG.config[key].connections
    rows = DataFrame(PormG.fetch(conn,
      "SELECT type, name FROM sqlite_master WHERE tbl_name = 'live_timing' AND name NOT LIKE 'sqlite_%' ORDER BY type, name"))
    @test collect(zip(rows.type, rows.name)) == [("index", "live_timing_driverref"), ("table", "live_timing")]
    @test Migrations.ensure_table!(timing, key) === :exists
  end

  _host1230_sqlite(change_db = false) do key
    timing = _host1230_timing()
    @test_logs (:warn, r"not set to change_db") @test Migrations.ensure_table!(timing, key) === :disabled
    rows = DataFrame(PormG.fetch(PormG.config[key].connections,
      "SELECT count(*) AS n FROM sqlite_master WHERE tbl_name = 'live_timing'"))
    @test rows[1, :n] == 0
  end

  @test_throws PormG.InvalidConfigurationError Migrations.ensure_table!(_host1230_timing(), "host1230_unloaded")

  # Inside an open transaction it refuses, as `run_once` does: the DDL would be a savepoint committed
  # only with the outer block, after the lock that serializes it is gone.
  _host1230_sqlite() do key
    err = try
      PormG.run_in_transaction(PormG.config[key].connections) do
        Migrations.ensure_table!(_host1230_timing(), key)
      end
      nothing
    catch e
      e
    end
    @test err isa PormG.TransactionError
    @test occursin("cannot run inside an open transaction", sprint(showerror, err))
  end
end
