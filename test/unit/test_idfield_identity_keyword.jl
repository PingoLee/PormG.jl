"""
`IDField(auto_increment = …)` is refused; `generated` is the one keyword that controls identity (#1334).

`IDField` accepted `auto_increment`, stored it, and no DDL path read it. On PostgreSQL the identity
follows `generated`, and SQLite and MySQL render AUTOINCREMENT/AUTO_INCREMENT on every `IDField`
key. So `IDField(auto_increment = false)` read as "a key the database does not generate" and still
rendered `"id" bigint PRIMARY KEY UNIQUE NOT NULL GENERATED BY DEFAULT AS IDENTITY`. The keyword now
raises `FieldValidationError` pointing at `generated = false`, and the `sIDField.auto_increment`
slot is always `true`. Since #1393 `generated` decides the column on SQLite and MySQL too, and nothing
reads the slot (`test_idfield_generated_key.jl` covers the rest of #1393).

Rendering is hermetic (marker structs per engine, as in `test_key_type_round_trip.jl`). The
inspectdb testset uses a temp SQLite file created and introspected in-process.

The refusal testset and the inspectdb testset fail on the code before #1334; the DDL and
identity-delta testsets on the code before #1393, whose SQLite and MySQL DDL ignored `generated`. The
slot testset is a characterization pin.
"""
# julia --project=test/integration test/unit/test_idfield_identity_keyword.jl

using Test
using PormG
isdefined(Main, :SQLite) || include(joinpath(@__DIR__, "..", "load_drivers.jl"))
import PormG.Models as IIK_M
import PormG.ConnectionPool: SQLiteConnectionPool, fetch, close_pool!
import PormG.Migrations: convert_schema_to_models

struct IikPg <: PormG.PormGPostgres end
struct IikSl <: PormG.PormGSQLite end
struct IikMy <: PormG.PormGMySQL end

_iik_err(f) = try
  f(); nothing
catch e
  e
end
_iik_ddl(field, conn) = PormG.Dialect.field_to_column("raceid", field, conn)

@testset "IDField identity keyword (#1334)" begin

# What: `auto_increment` raises, whatever its value, and the message names `generated = false`.
# Expected DDL: none — the field never builds. Why: the keyword changed no column on any engine, so
# a declaration that says "the database does not generate this key" was silently an identity column.
@testset "auto_increment is refused, pointing at generated = false" begin
  for v in (false, true)
    e = _iik_err(() -> IIK_M.IDField(auto_increment = v))
    @test e isa FieldValidationError
    msg = sprint(showerror, e)
    @test occursin("`auto_increment` was removed in #1334", msg)
    @test occursin("IDField(generated = false)", msg)
    @test occursin("generate_models_from_db", msg)
  end
  # Its own reason, not #1333's generic "does not accept", even beside another keyword.
  e = _iik_err(() -> IIK_M.IDField(auto_increment = false, generated = false))
  @test occursin("removed in #1334", sprint(showerror, e))
  @test !occursin("does not accept", sprint(showerror, e))
  @test !(:auto_increment in IIK_M._accepted_field_kwargs("IDField"))
end

# What: the spellings that still work, with their DDL on all three engines. Why: `generated` is the
# keyword that controls identity, on every engine since #1393: `generated = false` is a key no engine
# fills — no identity, a SQLite `BIGINT` key that is not a rowid alias, no MySQL AUTO_INCREMENT.
# (Moved by #1393: SQLite and MySQL rendered AUTOINCREMENT/AUTO_INCREMENT for it, the issue's item 2.)
@testset "generated controls identity; the DDL per engine" begin
  bare, always, supplied = IIK_M.IDField(), IIK_M.IDField(generated_always = true), IIK_M.IDField(generated = false)

  @test _iik_ddl(bare, IikPg()) == "\"raceid\" bigint PRIMARY KEY UNIQUE NOT NULL GENERATED BY DEFAULT AS IDENTITY"
  @test _iik_ddl(always, IikPg()) == "\"raceid\" bigint PRIMARY KEY UNIQUE NOT NULL GENERATED ALWAYS AS IDENTITY"
  @test _iik_ddl(supplied, IikPg()) == "\"raceid\" bigint PRIMARY KEY UNIQUE NOT NULL"

  for f in (bare, always)
    @test _iik_ddl(f, IikSl()) == "\"raceid\" INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE NOT NULL"
    @test _iik_ddl(f, IikMy()) == "`raceid` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY"
  end
  @test _iik_ddl(supplied, IikSl()) == "\"raceid\" BIGINT PRIMARY KEY UNIQUE NOT NULL"
  @test _iik_ddl(supplied, IikMy()) == "`raceid` BIGINT NOT NULL PRIMARY KEY"
end

# What: moving from the old spelling to `generated = false` is an identity change on every engine.
# Why: the upgrade entries tell the user `makemigrations` plans it — dropping the identity on
# PostgreSQL, a rebuild on SQLite, a MODIFY on MySQL; this is that plan's input. (Moved by #1393: the
# delta was empty on SQLite and MySQL, which ignored `generated`.)
@testset "generated = false is an identity delta on every engine" begin
  delta(conn) = PormG.Migrations.column_delta(IIK_M.IDField(generated = false), IIK_M.IDField(), conn;
                                              name = "raceid").changed
  @test :identity in delta(IikPg())
  @test :identity in delta(IikSl())
  @test :identity in delta(IikMy())
end

# What: the slot is `true` on every IDField. Why: the maintainer's decision for #1334 kept the slot;
# only `auto_increment = false` could set it to `false`, and that is refused now. Since #1393 the
# write paths read `generated` instead (`Models._database_generates`).
@testset "the auto_increment slot is always true" begin
  for f in (IIK_M.IDField(), IIK_M.IDField(generated = false), IIK_M.IDField(generated_always = true),
            IIK_M.IDField(null = false, primary_key = true))
    @test f.auto_increment === true
  end
  # A model written out never carries the keyword, so its file reloads.
  m = IIK_M.Model("race_source"; raceid = IIK_M.IDField(generated = false),
                  name = IIK_M.CharField(max_length = 255))
  src = IIK_M.Model_to_str(m)
  @test occursin("raceid = Models.IDField(generated=false)", src)
  @test !occursin("auto_increment", src)
end

# What: inspectdb on SQLite builds an IDField for an integer key that is not an exact `INTEGER`
# (`BIGINT PRIMARY KEY`) and for a key of no PormG type (`REAL PRIMARY KEY`), without the keyword;
# since #1393 both are `generated = false` (not rowid aliases, so SQLite does not fill them).
# Why: both readers passed `auto_increment = false`, which now raises — and wrote it into generated
# models files.
@testset "inspectdb on SQLite no longer passes auto_increment" begin
  mktempdir() do dir
    pool = SQLiteConnectionPool(joinpath(dir, "iik.sqlite"); pool_size = 1)
    try
      fetch(pool, """CREATE TABLE "race_big" ("raceid" BIGINT PRIMARY KEY NOT NULL, "name" TEXT(50) NOT NULL)""")
      fetch(pool, """CREATE TABLE "race_real" ("raceid" REAL PRIMARY KEY NOT NULL)""")
      fetch(pool, """CREATE TABLE "race_int" ("raceid" INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE NOT NULL)""")
      live = Base.CoreLogging.with_logger(Base.CoreLogging.NullLogger()) do
        convert_schema_to_models(pool; include_table = ["race_big", "race_real", "race_int"])
      end
      by = Dict(lowercase(string(m.name)) => m for m in live)
      for (t, generated) in ("race_big" => false, "race_real" => false, "race_int" => true)
        f = by[t].fields["raceid"]
        @test f isa IIK_M.sIDField
        @test f.primary_key && f.auto_increment
        @test f.generated === generated
        @test !occursin("auto_increment", IIK_M.Model_to_str(by[t]))
      end
    finally
      close_pool!(pool)
    end
  end
end

end
